// A token tree as CSS text: one custom property per token, the base in `:root` and under its own
// theme's name, so a region can switch back to it, and each other theme in a `[data-theme]` block. The same tokens always give the same bytes. A value DTCG has
// no CSS for is a composite type; it reaches the stylesheet only as raw CSS.
const PATH_SEPARATOR = ".";
const RAW_CSS_EXTENSION = "dev.ai-driven.css";
const HEADER = "/* Generated by aidd-ui.cjs tokens. Do not edit: change a token, then run the command again. */";
const INDENT = "  ";
const LINE_BREAK = "\n";
const PARAGRAPH_BREAK = "\n\n";
const OWN_FUNCTION_SPACES = ["hsl", "hwb", "lab", "lch", "oklab", "oklch"];
const OPAQUE = 1;
const HAS_SPACE = /\s/;

/** A token's CSS custom property, `--` plus its path joined by `-`. */
const customProperty = (name) => `--${name.split(PATH_SEPARATOR).join("-")}`;

/** A color as its hex when it has one and is opaque, else the CSS function of its space. */
function colorOf({ colorSpace, components, alpha, hex }) {
  const opaque = alpha === undefined || alpha >= OPAQUE;
  if (hex !== undefined && opaque) return hex;
  const parts = components.join(" ");
  const tail = opaque ? "" : ` / ${alpha}`;
  return OWN_FUNCTION_SPACES.includes(colorSpace) ? `${colorSpace}(${parts}${tail})` : `color(${colorSpace} ${parts}${tail})`;
}

/** A font family list, a name holding a space in quotes. */
const familyOf = (value) => [value].flat().map((name) => (HAS_SPACE.test(name) ? `"${name}"` : name)).join(", ");

const MEASURE = ({ value, unit }) => `${value}${unit}`;
const AS_IS = (value) => String(value);

const WRITERS = {
  color: colorOf,
  dimension: MEASURE,
  duration: MEASURE,
  number: AS_IS,
  fontWeight: AS_IS,
  fontFamily: familyOf,
  cubicBezier: (points) => `cubic-bezier(${points.join(", ")})`,
};

/** A token value of `type` as CSS; null for a composite type, which has none. */
const valueOf = (type, value) => (Object.hasOwn(WRITERS, type) ? WRITERS[type](value) : null);

/** A declaration's value: raw CSS verbatim, an alias as the var() of its target, else the value. */
function declarationOf(entry) {
  if (entry.raw !== undefined) return entry.raw;
  if (entry.alias !== undefined) return `var(${customProperty(entry.alias)})`;
  return valueOf(entry.type, entry.value);
}

const block = (selector, declarations) => [`${selector} {`, ...declarations.map(([name, value]) => `${INDENT}${customProperty(name)}: ${value};`), "}"];

/** The stylesheet of `base`, named `baseTheme`, then of each `{theme, tokens}` of `themes` in order, with the
 * problems naming each token that has no CSS. Each token is `{name, type, value | alias | raw, file}`.
 * `css` is null when a problem remains. */
function render({ base, baseTheme, themes }) {
  const problems = [];
  const declare = (tokens) =>
    tokens.flatMap((entry) => {
      const value = declarationOf(entry);
      if (value === null) problems.push({ file: entry.file, message: `${entry.name}: a ${entry.type} has no CSS of its own, give it a ${RAW_CSS_EXTENSION} value` });
      return value === null ? [] : [[entry.name, value]];
    });
  const baseSelector = baseTheme === undefined ? ":root" : `:root, [data-theme="${baseTheme}"]`;
  const blocks = [block(baseSelector, declare(base)), ...themes.map(({ theme, tokens }) => block(`[data-theme="${theme}"]`, declare(tokens)))];
  return { css: problems.length ? null : `${[HEADER, ...blocks.map((lines) => lines.join(LINE_BREAK))].join(PARAGRAPH_BREAK)}${LINE_BREAK}`, problems };
}

module.exports = { valueOf, render, customProperty };
