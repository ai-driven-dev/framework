// A token tree as CSS text, and a stylesheet read back as rules and custom properties by line: one custom property per token, the base in `:root` and under its own
// theme's name, so a region can switch back to it. Every context a nested region can be in is
// resolved as the Resolver does, the modifier later in `resolutionOrder` winning, and a block holds
// only what the cascade would not already give that element: each other theme in a `[data-theme]`
// block, each platform but the default in a `[data-platform]` block, each pair of them in a block
// of the platform holding the theme, then each breakpoint repeating those selectors in an `@media`
// block. A theme or platform block also redeclares the tokens that depend on one it redefines,
// since a `var()` computes where it is declared: otherwise a nested region keeps their base value.
// The same tokens always give the same bytes. A value DTCG has no CSS for is a composite type; it
// reaches the stylesheet only as raw CSS.
const PATH_SEPARATOR = ".";
const RAW_CSS_EXTENSION = "dev.ai-driven.css"; // a CSS value DTCG cannot hold, such as color-mix() or 100%
const HEADER = "/* Generated by aidd-ui.cjs tokens. Do not edit: change a token, then run the command again. */";
const INDENT = "  ";
const LINE_BREAK = "\n";
const PARAGRAPH_BREAK = "\n\n";
const OWN_FUNCTION_SPACES = ["hsl", "hwb", "lab", "lch", "oklab", "oklch"];
const OPAQUE = 1;
const HAS_SPACE = /\s/;
const VAR_REFERENCE = /var\(\s*(--[\w-]+)/g; // the custom property a `var()` names

const COMMENT = /\/\*[\s\S]*?\*\//g;
const NOT_LINE_BREAK = /[^\n]/g;
const VAR_CALL = /var\(\s*(--[\w-]+)\s*(?:,[^)]*)?\)/g;
const CUSTOM_PROPERTY = /^(\s*)(--[\w-]+)\s*:([\s\S]*)$/;
const MEDIA_RULE = /^@media\s+([\s\S]*)$/;
const AT_RULE = "@";
const BASE_KEY = ""; // a stylesheet's custom properties by selector: the base, `:root`, under this key
const MEDIA_PREFIX = "@media ";
const SELECTOR_JOIN = "\n"; // a breakpoint's key, then the selector it repeats
const ATTRIBUTE = /\[data-(theme|platform)="[^"]+"\]/g;
const WHITESPACE = /\s+/g;
const compareKinds = (a, b) => (a === b ? 0 : a === "theme" ? -1 : 1); // a pair's theme block is written before its platform's

/** A stylesheet with its comments blanked and its lines kept, so a position still names its line. */
const blankComments = (css) => css.replace(COMMENT, (found) => found.replace(NOT_LINE_BREAK, " "));

const lineAt = (text, offset) => text.slice(0, offset).split(LINE_BREAK).length;

/** The offset of the `}` closing a block whose body starts at `from`; a quoted string hides braces. */
function closeOf(text, from) {
  let depth = 1;
  let quote = null;
  for (let at = from; at < text.length; at += 1) {
    const char = text[at];
    if (quote) {
      if (char === "\\") at += 1;
      else if (char === quote) quote = null;
    } else if (char === '"' || char === "'") quote = char;
    else if (char === "{") depth += 1;
    else if (char === "}" && (depth -= 1) === 0) return at;
  }
  return text.length;
}

/** The rules of a stylesheet as `{media, selector, body, line, bodyLine}`, `media` being the query of
 * the `@media` block holding a rule, else null; and the other at-rules, nested ones included, as
 * `{prelude, body, line, bodyLine}`. A statement such as `@import` is neither. */
function rulesOf(css) {
  const text = blankComments(css);
  const rules = [];
  const others = [];
  const scan = (from, to, media) => {
    let at = from;
    for (;;) {
      const open = text.indexOf("{", at);
      if (open < 0 || open >= to) return;
      const statement = text.indexOf(";", at);
      if (statement >= 0 && statement < open) {
        at = statement + 1;
        continue;
      }
      const close = closeOf(text, open + 1);
      const prelude = text.slice(at, open).trim();
      const start = at + text.slice(at, open).indexOf(prelude);
      const block = { line: lineAt(text, start), bodyLine: lineAt(text, open + 1), body: text.slice(open + 1, close) };
      const query = media === null ? MEDIA_RULE.exec(prelude)?.[1].trim() : undefined;
      if (query !== undefined) scan(open + 1, close, query);
      else if (prelude.startsWith(AT_RULE)) others.push({ prelude, ...block });
      else rules.push({ media, selector: prelude, ...block });
      at = close + 1;
    }
  };
  scan(0, text.length, null);
  return { rules, others };
}

/** The custom properties a rule's body declares, `{name, value, line}`: the value as written,
 * trimmed, the last declaration needing no `;`. A `;` inside quotes or parentheses ends nothing. */
function declarationsIn(body, bodyLine) {
  const found = [];
  let begin = 0;
  let depth = 0;
  let quote = null;
  const end = (at) => {
    const statement = body.slice(begin, at);
    const match = CUSTOM_PROPERTY.exec(statement);
    if (match) found.push({ name: match[2], value: match[3].trim(), line: bodyLine + body.slice(0, begin + match[1].length).split(LINE_BREAK).length - 1 });
    begin = at + 1;
  };
  for (let at = 0; at < body.length; at += 1) {
    const char = body[at];
    if (quote) {
      if (char === "\\") at += 1;
      else if (char === quote) quote = null;
    } else if (char === '"' || char === "'") quote = char;
    else if (char === "(") depth += 1;
    else if (char === ")") depth -= 1;
    else if (char === ";" && depth === 0) end(at);
  }
  end(body.length);
  return found;
}

/** A generated stylesheet's custom properties by selector: the base, `:root`, under BASE_KEY; a
 * breakpoint of the base under its query, and under its query then the selector it repeats. */
function declarationsOf(css) {
  const found = new Map();
  for (const { media, selector, body, bodyLine } of rulesOf(css).rules) {
    const shown = selector.replace(WHITESPACE, " ");
    const own = shown.includes(":root") ? BASE_KEY : shown;
    const key = media === null ? own : own === BASE_KEY ? `${MEDIA_PREFIX}${media}` : `${MEDIA_PREFIX}${media}${SELECTOR_JOIN}${own}`;
    const values = found.get(key) ?? new Map();
    for (const { name, value } of declarationsIn(body, bodyLine)) values.set(name, value);
    found.set(key, values);
  }
  return found;
}

/** The keys of `declarationsOf` whose custom properties are in force on an element `key` stands
 * for, the weakest first: the base, the base's breakpoint, the theme and the platform of a pair,
 * the selector, its breakpoint. */
function layersOf(key) {
  const at = key.indexOf(SELECTOR_JOIN);
  const [media, selector] = at < 0 ? (key.startsWith(MEDIA_PREFIX) ? [key, BASE_KEY] : [undefined, key]) : [key.slice(0, at), key.slice(at + SELECTOR_JOIN.length)];
  const singles = [...new Map([...selector.matchAll(ATTRIBUTE)].map(([found, kind]) => [found, kind]))].sort(([, a], [, b]) => compareKinds(a, b)).map(([found]) => found);
  return [...new Set([BASE_KEY, ...(media === undefined || selector === BASE_KEY ? [] : [media]), ...(singles.length > 1 ? singles : []), selector, key])];
}

/** The custom properties in force on an element `key` of a stylesheet read by `declarationsOf` stands for. */
const layered = (sheet, key) => new Map(layersOf(key).flatMap((each) => [...(sheet.get(each) ?? [])]));

/** A custom property's value with each `var()` it holds replaced by its target's, down to a value. */
function resolved(values, name, path = new Set()) {
  const value = values.get(name);
  if (value === undefined || path.has(name)) return value;
  return value.replace(VAR_CALL, (call, target) => resolved(values, target, new Set([...path, name])) ?? call);
}

/** A token's CSS custom property, `--` plus its path joined by `-`. */
const customProperty = (name) => `--${name.split(PATH_SEPARATOR).join("-")}`;

/** A color as its hex when it has one and is opaque, else the CSS function of its space. */
function colorOf({ colorSpace, components, alpha, hex }) {
  const opaque = alpha === undefined || alpha >= OPAQUE;
  if (hex !== undefined && opaque) return hex;
  const parts = components.join(" ");
  const tail = opaque ? "" : ` / ${alpha}`;
  return OWN_FUNCTION_SPACES.includes(colorSpace) ? `${colorSpace}(${parts}${tail})` : `color(${colorSpace} ${parts}${tail})`;
}

/** A font family list, a name holding a space in quotes. */
const familyOf = (value) => [value].flat().map((name) => (HAS_SPACE.test(name) ? `"${name}"` : name)).join(", ");

/** DTCG's font weight keywords and the number each stands for: CSS reads few of them. */
const FONT_WEIGHTS = {
  thin: 100,
  hairline: 100,
  "extra-light": 200,
  "ultra-light": 200,
  light: 300,
  normal: 400,
  regular: 400,
  book: 400,
  medium: 500,
  "semi-bold": 600,
  "demi-bold": 600,
  bold: 700,
  "extra-bold": 800,
  "ultra-bold": 800,
  black: 900,
  heavy: 900,
  "extra-black": 950,
  "ultra-black": 950,
};

const MEASURE = ({ value, unit }) => `${value}${unit}`;
const AS_IS = (value) => String(value);

const WRITERS = {
  color: colorOf,
  dimension: MEASURE,
  duration: MEASURE,
  number: AS_IS,
  fontWeight: (value) => String(FONT_WEIGHTS[value] ?? value),
  fontFamily: familyOf,
  cubicBezier: (points) => `cubic-bezier(${points.join(", ")})`,
};

/** A token value of `type` as CSS; null for a composite type, which has none. */
const valueOf = (type, value) => (Object.hasOwn(WRITERS, type) ? WRITERS[type](value) : null);

/** A declaration's value: raw CSS verbatim, an alias as the var() of its target, else the value. */
function declarationOf(entry) {
  if (entry.raw !== undefined) return entry.raw;
  if (entry.alias !== undefined) return `var(${customProperty(entry.alias)})`;
  return valueOf(entry.type, entry.value);
}

/** The custom properties a token's declaration cites: its alias's target, or each var() of its raw CSS. */
function citedBy(entry) {
  if (typeof entry.raw === "string") return [...entry.raw.matchAll(VAR_REFERENCE)].map((match) => match[1]);
  return entry.alias === undefined ? [] : [customProperty(entry.alias)];
}

/** The tokens of `base`, in its order, that depend on one of `redefined`, transitively, and are not
 * among them. */
function dependents(base, redefined) {
  const own = new Set(redefined.map((entry) => customProperty(entry.name)));
  const reached = new Set(own);
  for (let grew = true; grew; ) {
    grew = false;
    for (const entry of base) {
      const name = customProperty(entry.name);
      if (reached.has(name) || !citedBy(entry).some((cited) => reached.has(cited))) continue;
      reached.add(name);
      grew = true;
    }
  }
  return base.filter((entry) => reached.has(customProperty(entry.name)) && !own.has(customProperty(entry.name)));
}

/** The custom property `entry` cites that leads back to it among `declarations`; undefined when none does. */
function loopOf(declarations, entry) {
  const back = new Set([entry, ...dependents(declarations, [entry])].map((each) => customProperty(each.name)));
  return citedBy(entry).find((cited) => back.has(cited));
}

const block = (selector, declarations) => [`${selector} {`, ...declarations.map(([name, value]) => `${INDENT}${customProperty(name)}: ${value};`), "}"];

/** A rule block nested in an `@media` block. */
const mediaBlock = (media, lines) => [`@media ${media} {`, ...lines.map((line) => `${INDENT}${line}`), "}"];

const DEFAULT_ORDER = ["theme", "platform", "breakpoint"];
const keyed = (tokens) => new Map(tokens.map((entry) => [entry.name, entry]));

/** Whether a selector `alt` matches the last element of `chain`, its ancestors before it. */
function matches(alt, chain) {
  const last = chain.at(-1);
  if (alt.root) return chain.length === 1;
  const platformed = alt.platform === undefined || (alt.within ? chain.slice(0, -1).some((each) => each.platform === alt.platform) : last.platform === alt.platform);
  return (alt.theme === undefined || last.theme === alt.theme) && platformed;
}

/** The stylesheet of `base`, named `baseTheme`, then of each `{theme, tokens}` of `themes`, each
 * `{platform, tokens}` of `platforms` and each `{media, tokens}` of `breakpoints`, with the problems
 * naming each token that has no CSS. Each token is `{name, type, value | alias | raw, file}`. A context
 * holds a token name once; for a combination of contexts, `order` names the modifiers from the
 * weakest to the one that wins. `css` is null when a problem remains. */
function render({ base, baseTheme, themes, platforms = [], breakpoints = [], order = DEFAULT_ORDER }) {
  const problems = [];
  const declare = (entries) =>
    entries.flatMap((entry) => {
      const value = declarationOf(entry);
      if (value === null && !problems.some((each) => each.file === entry.file && each.message.startsWith(`${entry.name}:`))) problems.push({ file: entry.file, message: `${entry.name}: a ${entry.type} has no CSS of its own, give it a ${RAW_CSS_EXTENSION} value` });
      return value === null ? [] : [[entry.name, value]];
    });
  const overlays = {
    theme: new Map(themes.map(({ theme, tokens }) => [theme, keyed(tokens)])),
    platform: new Map(platforms.map(({ platform, tokens }) => [platform, keyed(tokens)])),
    breakpoint: new Map(breakpoints.map((each) => [each, keyed(each.tokens)])),
  };
  /** Each token's entry in a context `{theme?, platform?, breakpoint?}`, each modifier overriding the earlier. */
  const resolve = (context) => {
    const found = keyed(base);
    for (const modifier of order) for (const [name, entry] of overlays[modifier].get(context[modifier]) ?? []) found.set(name, entry);
    return found;
  };
  const names = [...new Set([...base.map((entry) => entry.name), ...Object.values(overlays).flatMap((each) => [...each.values()].flatMap((tokens) => [...tokens.keys()]))])];
  const planned = []; // {alts, spec, media, declared}, in stylesheet order
  /** The entry that wins for `name` on the last element of `chain` at the width of `active`. */
  const winner = (chain, name, active) => {
    for (let depth = chain.length; depth > 0; depth -= 1) {
      const element = chain.slice(0, depth);
      let best;
      for (const each of planned) if (each.declared.has(name) && (each.media === null || each.media === active) && each.alts.some((alt) => matches(alt, element)) && (best === undefined || each.spec >= best.spec)) best = each;
      if (best) return best.declared.get(name);
    }
    return undefined;
  };
  const baseSelector = baseTheme === undefined ? ":root" : `:root, [data-theme="${baseTheme}"]`;
  const attribute = (kind, value) => `[data-${kind}="${value}"]`;
  const bareThemes = themes.map(({ theme }) => theme);
  const scopes = [
    { selector: baseSelector, alts: [{ root: true }], spec: 1, context: {}, chains: [[{}]], settled: true },
    ...bareThemes.map((theme) => ({ selector: attribute("theme", theme), alts: [{ theme }], spec: 1, context: { theme }, chains: [[{}, { theme }]], dependents: true, always: true })),
    ...platforms.map(({ platform }) => ({ selector: attribute("platform", platform), alts: [{ platform }], spec: 1, context: { platform }, chains: [[{}, { platform }]], dependents: true })),
    ...platforms.flatMap(({ platform }) =>
      bareThemes.map((theme) => ({
        selector: `${attribute("platform", platform)} ${attribute("theme", theme)}, ${attribute("platform", platform)}${attribute("theme", theme)}`,
        alts: [{ theme, platform, within: true }, { theme, platform }],
        spec: 2,
        context: { theme, platform },
        chains: [[{}, { platform }, { theme }], [{}, { theme, platform }]],
      }))
    ),
  ];
  /** A scope's block at the width of `breakpoint`, or at none: the tokens the cascade would not give its elements, and for a theme or platform the dependents of those. Null when it holds none. */
  const plan = (scope, breakpoint = null) => {
    const target = resolve({ ...scope.context, breakpoint });
    const held = names.filter((name) => (scope.settled && breakpoint === null && target.has(name)) || scope.chains.some((chain) => winner(chain, name, breakpoint) !== target.get(name)));
    const redeclared = scope.dependents && breakpoint === null ? dependents([...target.values()], held.map((name) => target.get(name))).map((entry) => entry.name) : [];
    const declared = new Map([...held, ...redeclared].map((name) => [name, target.get(name)]));
    if (!declared.size && !(scope.always && breakpoint === null)) return null;
    planned.push({ alts: scope.alts, spec: scope.spec, media: breakpoint, declared });
    const lines = block(scope.selector, declare([...declared.values()]));
    return breakpoint === null ? lines : mediaBlock(breakpoint.media, lines);
  };
  const blocks = scopes.map((scope) => plan(scope));
  for (const breakpoint of breakpoints) blocks.push(...scopes.map((scope) => plan(scope, breakpoint)));
  return { css: problems.length ? null : `${[HEADER, ...blocks.filter(Boolean).map((lines) => lines.join(LINE_BREAK))].join(PARAGRAPH_BREAK)}${LINE_BREAK}`, problems };
}

