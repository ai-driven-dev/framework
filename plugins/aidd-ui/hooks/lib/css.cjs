// A token tree as CSS text, and a stylesheet read back as rules and custom properties by line: one
// custom property per token, all on the root element, so every `var()` computes against the final
// values there. A render sets `data-theme` and `data-platform` on `<html>` alone. After the base
// `:root` come the theme, the platform and the pair of both, each as `:root` plus its attributes, so
// the specificity grows with the combination, then each breakpoint repeating them in an `@media`
// block. A block holds the value the Resolver gives its combination, by `resolutionOrder`, for
// each token the cascade would not already give it. The same tokens always give the same bytes. A
// value DTCG has no CSS for is a composite type; it reaches the stylesheet only as raw CSS.
const { LINE_BREAK, blank, lineOf } = require("./markdown.cjs");
const { MODIFIERS } = require("./resolver.cjs");

const PATH_SEPARATOR = ".";
const RAW_CSS_EXTENSION = "dev.ai-driven.css"; // a CSS value DTCG cannot hold, such as color-mix() or 100%
const HEADER = "/* Generated by aidd-ui.cjs tokens. Do not edit: change a token, then run the command again. */";
const INDENT = "  ";
const PARAGRAPH_BREAK = "\n\n";
const OWN_FUNCTION_SPACES = ["hsl", "hwb", "lab", "lch", "oklab", "oklch"];
const OPAQUE = 1;
const HAS_SPACE = /\s/;
const VAR_REFERENCE = /var\(\s*(--[\w-]+)/g; // the custom property a `var()` names

const COMMENT = /\/\*[\s\S]*?\*\//g;
const VAR_CALL = /var\(\s*(--[\w-]+)\s*(?:,[^)]*)?\)/g;
const CUSTOM_PROPERTY = /^(\s*)(--[\w-]+)\s*:([\s\S]*)$/;
const MEDIA_RULE = /^@media\s+([\s\S]*)$/;
const AT_RULE = "@";
const BASE_KEY = ""; // a stylesheet's custom properties by selector: the base, `:root`, under this key
const MEDIA_PREFIX = "@media ";
const SELECTOR_JOIN = "\n"; // a breakpoint's key, then the selector it repeats
const ATTRIBUTE = /\[data-(theme|platform)="[^"]+"\]/g;
const WHITESPACE = /\s+/g;
const BASE_SELECTOR = /^:root(,|$)/; // `:root` alone, or the base theme beside it as an earlier stylesheet wrote it
const compareKinds = (a, b) => (a === b ? 0 : a === "theme" ? -1 : 1); // a pair's theme block is written before its platform's

/** A stylesheet with its comments blanked and its lines kept, so a position still names its line. */
const blankComments = (css) => css.replace(COMMENT, blank);

/** The offset of the `}` closing a block whose body starts at `from`; a quoted string hides braces. */
function closeOf(text, from) {
  let depth = 1;
  let quote = null;
  for (let at = from; at < text.length; at += 1) {
    const char = text[at];
    if (quote) {
      if (char === "\\") at += 1;
      else if (char === quote) quote = null;
    } else if (char === '"' || char === "'") quote = char;
    else if (char === "{") depth += 1;
    else if (char === "}" && (depth -= 1) === 0) return at;
  }
  return text.length;
}

/** The rules of a stylesheet as `{media, selector, body, line, bodyLine}`, `media` being the query of
 * the `@media` block holding a rule, else null; and the other at-rules, nested ones included, as
 * `{prelude, body, line, bodyLine}`. A statement such as `@import` is neither. */
function rulesOf(css) {
  const text = blankComments(css);
  const rules = [];
  const others = [];
  const scan = (from, to, media) => {
    let at = from;
    for (;;) {
      const open = text.indexOf("{", at);
      if (open < 0 || open >= to) return;
      const statement = text.indexOf(";", at);
      if (statement >= 0 && statement < open) {
        at = statement + 1;
        continue;
      }
      const close = closeOf(text, open + 1);
      const prelude = text.slice(at, open).trim();
      const start = at + text.slice(at, open).indexOf(prelude);
      const block = { line: lineOf(text, start), bodyLine: lineOf(text, open + 1), body: text.slice(open + 1, close) };
      const query = media === null ? MEDIA_RULE.exec(prelude)?.[1].trim() : undefined;
      if (query !== undefined) scan(open + 1, close, query);
      else if (prelude.startsWith(AT_RULE)) others.push({ prelude, ...block });
      else rules.push({ media, selector: prelude, ...block });
      at = close + 1;
    }
  };
  scan(0, text.length, null);
  return { rules, others };
}

/** The custom properties a rule's body declares, `{name, value, line}`: the value as written,
 * trimmed, the last declaration needing no `;`. A `;` inside quotes or parentheses ends nothing. */
function declarationsIn(body, bodyLine) {
  const found = [];
  let begin = 0;
  let depth = 0;
  let quote = null;
  const end = (at) => {
    const statement = body.slice(begin, at);
    const match = CUSTOM_PROPERTY.exec(statement);
    if (match) found.push({ name: match[2], value: match[3].trim(), line: bodyLine + lineOf(body, begin + match[1].length) - 1 });
    begin = at + 1;
  };
  for (let at = 0; at < body.length; at += 1) {
    const char = body[at];
    if (quote) {
      if (char === "\\") at += 1;
      else if (char === quote) quote = null;
    } else if (char === '"' || char === "'") quote = char;
    else if (char === "(") depth += 1;
    else if (char === ")") depth -= 1;
    else if (char === ";" && depth === 0) end(at);
  }
  end(body.length);
  return found;
}

/** A generated stylesheet's custom properties by selector: the base, `:root`, under BASE_KEY; a
 * breakpoint of the base under its query, and under its query then the selector it repeats. */
function declarationsOf(css) {
  const found = new Map();
  for (const { media, selector, body, bodyLine } of rulesOf(css).rules) {
    const shown = selector.replace(WHITESPACE, " ");
    const own = BASE_SELECTOR.test(shown) ? BASE_KEY : shown;
    const key = media === null ? own : joinKey(`${MEDIA_PREFIX}${media}`, own);
    const values = found.get(key) ?? new Map();
    for (const { name, value } of declarationsIn(body, bodyLine)) values.set(name, value);
    found.set(key, values);
  }
  return found;
}

const joinKey = (media, selector) => (selector === BASE_KEY ? media : `${media}${SELECTOR_JOIN}${selector}`);

/** A key of `declarationsOf` as `[media, selector]`, `media` being undefined outside a breakpoint. */
function splitKey(key) {
  const at = key.indexOf(SELECTOR_JOIN);
  if (at >= 0) return [key.slice(0, at), key.slice(at + SELECTOR_JOIN.length)];
  return key.startsWith(MEDIA_PREFIX) ? [key, BASE_KEY] : [undefined, key];
}

/** The keys of `declarationsOf` whose custom properties are in force on the root carrying the
 * attributes of `key`, the weakest first: by specificity, the base, the theme and the platform, the
 * pair; at one specificity, a breakpoint's rule after the others. */
function layersOf(key) {
  const [media, selector] = splitKey(key);
  const singles = [...new Map([...selector.matchAll(ATTRIBUTE)].map(([found, kind]) => [found, kind]))].sort(([, a], [, b]) => compareKinds(a, b)).map(([found]) => `:root${found}`);
  const levels = selector === BASE_KEY ? [[BASE_KEY]] : singles.length > 1 ? [[BASE_KEY], singles, [selector]] : [[BASE_KEY], [selector]];
  return levels.flatMap((level) => [...level, ...(media === undefined ? [] : level.map((each) => joinKey(media, each)))]);
}

/** The custom properties in force on the root `key` of a stylesheet read by `declarationsOf` stands for. */
const layered = (sheet, key) => new Map(layersOf(key).flatMap((each) => [...(sheet.get(each) ?? [])]));

/** The roots a stylesheet read by `declarationsOf` can be asked about, as keys: each selector all
 * `sheets` hold, alone and at each query any of them holds. */
function contextsOf(sheets) {
  const split = sheets.map((sheet) => [...sheet.keys()].map(splitKey));
  const selectorsOf = (parts) => new Set([BASE_KEY, ...parts.filter(([media]) => media === undefined).map(([, selector]) => selector)]);
  const queries = [...new Set(split.flatMap((parts) => parts.map(([media]) => media).filter(Boolean)))];
  return [...selectorsOf(split[0])].filter((selector) => split.every((parts) => selectorsOf(parts).has(selector))).flatMap((selector) => [selector, ...queries.map((media) => joinKey(media, selector))]);
}

/** A custom property's value with each `var()` it holds replaced by its target's, down to a value. */
function resolved(values, name, path = new Set()) {
  const value = values.get(name);
  if (value === undefined || path.has(name)) return value;
  return value.replace(VAR_CALL, (call, target) => resolved(values, target, new Set([...path, name])) ?? call);
}

/** A token's CSS custom property, `--` plus its path joined by `-`. */
const customProperty = (name) => `--${name.split(PATH_SEPARATOR).join("-")}`;

/** A color as its hex when it has one and is opaque, else the CSS function of its space. */
function colorOf({ colorSpace, components, alpha, hex }) {
  const opaque = alpha === undefined || alpha >= OPAQUE;
  if (hex !== undefined && opaque) return hex;
  const parts = components.join(" ");
  const tail = opaque ? "" : ` / ${alpha}`;
  return OWN_FUNCTION_SPACES.includes(colorSpace) ? `${colorSpace}(${parts}${tail})` : `color(${colorSpace} ${parts}${tail})`;
}

/** A font family list, a name holding a space in quotes. */
const familyOf = (value) => [value].flat().map((name) => (HAS_SPACE.test(name) ? `"${name}"` : name)).join(", ");

/** DTCG's font weight keywords and the number each stands for: CSS reads few of them. */
const FONT_WEIGHTS = {
  thin: 100,
  hairline: 100,
  "extra-light": 200,
  "ultra-light": 200,
  light: 300,
  normal: 400,
  regular: 400,
  book: 400,
  medium: 500,
  "semi-bold": 600,
  "demi-bold": 600,
  bold: 700,
  "extra-bold": 800,
  "ultra-bold": 800,
  black: 900,
  heavy: 900,
  "extra-black": 950,
  "ultra-black": 950,
};

const MEASURE = ({ value, unit }) => `${value}${unit}`;
const AS_IS = (value) => String(value);

const WRITERS = {
  color: colorOf,
  dimension: MEASURE,
  duration: MEASURE,
  number: AS_IS,
  fontWeight: (value) => String(FONT_WEIGHTS[value] ?? value),
  fontFamily: familyOf,
  cubicBezier: (points) => `cubic-bezier(${points.join(", ")})`,
};

/** A token value of `type` as CSS; null for a composite type, which has none. */
const valueOf = (type, value) => (Object.hasOwn(WRITERS, type) ? WRITERS[type](value) : null);

/** A declaration's value: raw CSS verbatim, an alias as the var() of its target, else the value. */
function declarationOf(entry) {
  if (entry.raw !== undefined) return entry.raw;
  if (entry.alias !== undefined) return `var(${customProperty(entry.alias)})`;
  return valueOf(entry.type, entry.value);
}

/** The custom properties a token's declaration cites: its alias's target, or each var() of its raw CSS. */
function citedBy(entry) {
  if (typeof entry.raw === "string") return [...entry.raw.matchAll(VAR_REFERENCE)].map((match) => match[1]);
  return entry.alias === undefined ? [] : [customProperty(entry.alias)];
}

/** The tokens of `base`, in its order, that depend on one of `redefined`, transitively, and are not
 * among them. */
function dependents(base, redefined) {
  const own = new Set(redefined.map((entry) => customProperty(entry.name)));
  const reached = new Set(own);
  for (let grew = true; grew; ) {
    grew = false;
    for (const entry of base) {
      const name = customProperty(entry.name);
      if (reached.has(name) || !citedBy(entry).some((cited) => reached.has(cited))) continue;
      reached.add(name);
      grew = true;
    }
  }
  return base.filter((entry) => reached.has(customProperty(entry.name)) && !own.has(customProperty(entry.name)));
}

/** The custom property `entry` cites that leads back to it among `declarations`; undefined when none does. */
function loopOf(declarations, entry) {
  const back = new Set([entry, ...dependents(declarations, [entry])].map((each) => customProperty(each.name)));
  return citedBy(entry).find((cited) => back.has(cited));
}

const block = (selector, declarations) => [`${selector} {`, ...declarations.map(([name, value]) => `${INDENT}${customProperty(name)}: ${value};`), "}"];

const keyed = (tokens) => new Map(tokens.map((entry) => [entry.name, entry]));
const attribute = (kind, value) => `[data-${kind}="${value}"]`;

/** The stylesheet of `base`, then of each `{theme, tokens}` of `themes`, each `{platform, tokens}`
 * of `platforms` and each `{media, tokens}` of `breakpoints`, with the problems naming each token
 * that has no CSS. Each token is `{name, type, value | alias | raw, file}`. A context holds a token
 * name once; for a combination of contexts, `order` names the modifiers from the weakest to the
 * one that wins. `css` is null when a problem remains. */
function render({ base, themes, platforms = [], breakpoints = [], order = MODIFIERS }) {
  const problems = [];
  for (const entry of [base, ...themes, ...platforms, ...breakpoints].flatMap((each) => each.tokens ?? each)) {
    if (declarationOf(entry) === null && !problems.some((each) => each.file === entry.file && each.message.startsWith(`${entry.name}:`))) problems.push({ file: entry.file, message: `${entry.name}: a ${entry.type} has no CSS of its own, give it a ${RAW_CSS_EXTENSION} value` });
  }
  const overlays = {
    theme: new Map(themes.map(({ theme, tokens }) => [theme, keyed(tokens)])),
    platform: new Map(platforms.map(({ platform, tokens }) => [platform, keyed(tokens)])),
    breakpoint: new Map(breakpoints.map((each) => [each, keyed(each.tokens)])),
  };
  /** Each token's entry in a context `{theme?, platform?, breakpoint?}`, each modifier overriding the earlier. */
  const resolve = (context) => {
    const found = keyed(base);
    for (const modifier of order) for (const [name, entry] of overlays[modifier].get(context[modifier]) ?? []) found.set(name, entry);
    return found;
  };
  const names = [...new Set([...base.map((entry) => entry.name), ...Object.values(overlays).flatMap((each) => [...each.values()].flatMap((tokens) => [...tokens.keys()]))])];
  // The base, then each theme, each platform and each pair of both: the weight of a selector is its parts, `:root` included.
  const scopes = [
    { selector: ":root", context: {} },
    ...themes.map(({ theme }) => ({ selector: `:root${attribute("theme", theme)}`, context: { theme }, listed: true })),
    ...platforms.map(({ platform }) => ({ selector: `:root${attribute("platform", platform)}`, context: { platform } })),
    ...platforms.flatMap(({ platform }) => themes.map(({ theme }) => ({ selector: `:root${attribute("platform", platform)}${attribute("theme", theme)}`, context: { theme, platform } }))),
  ].map((scope) => ({ ...scope, weight: 1 + Object.keys(scope.context).length }));
  const planned = []; // {scope, width, declared}, in stylesheet order
  /** The text the blocks planned so far give `name` on the root carrying `context`, at the width of `width`: the heaviest block wins, the later one a tie. */
  const given = (context, width, name) => {
    let best;
    for (const each of planned) {
      const { theme, platform } = each.scope.context;
      const fits = (theme === undefined || theme === context.theme) && (platform === undefined || platform === context.platform) && (each.width === null || each.width === width);
      if (fits && each.declared.has(name) && (best === undefined || each.scope.weight >= best.scope.weight)) best = each;
    }
    return best?.declared.get(name);
  };
  /** A scope's rule at the width of `width`, or at none: the tokens the cascade would not give its root. Null when it holds none. */
  const plan = (scope, width = null) => {
    const target = resolve({ ...scope.context, breakpoint: width });
    const wanted = names.map((name) => [name, target.has(name) ? declarationOf(target.get(name)) : undefined]);
    const declared = new Map(wanted.filter(([name, text]) => given(scope.context, width, name) !== text));
    if (!declared.size && !(scope.listed && width === null)) return null;
    planned.push({ scope, width, declared });
    return block(scope.selector, [...declared].filter(([, value]) => value !== null));
  };
  const blocks = scopes.map((scope) => plan(scope));
  for (const breakpoint of breakpoints) {
    const rules = scopes.map((scope) => plan(scope, breakpoint)).filter(Boolean);
    if (rules.length) blocks.push([`@media ${breakpoint.media} {`, ...rules.flat().map((line) => `${INDENT}${line}`), "}"]);
  }
  return { css: problems.length ? null : `${[HEADER, ...blocks.filter(Boolean).map((lines) => lines.join(LINE_BREAK))].join(PARAGRAPH_BREAK)}${LINE_BREAK}`, problems };
}

module.exports = { FONT_WEIGHTS, RAW_CSS_EXTENSION, VAR_REFERENCE, HEADER, render, customProperty, citedBy, loopOf, rulesOf, declarationsIn, declarationsOf, layered, contextsOf, resolved };
