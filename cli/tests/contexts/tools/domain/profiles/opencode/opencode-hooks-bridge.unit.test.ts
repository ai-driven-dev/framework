import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { describe, expect, it } from "vitest";
import {
  generateOpencodeHooksBridge,
  parseHooksJsonForBridge,
} from "../../../../../../src/contexts/tools/domain/profiles/opencode/opencode-hooks-bridge.js";

// Built rather than written as a literal "${CLAUDE_PLUGIN_ROOT}" string: biome reads a plain
// string holding "${...}" as a forgotten template literal.
const ROOT = "$" + "{CLAUDE_PLUGIN_ROOT}";

const THREE_EVENT_HOOKS_JSON = JSON.stringify({
  hooks: {
    SessionStart: [
      { hooks: [{ type: "command", command: `node ${ROOT}/hooks/update_memory.js` }] },
    ],
    Stop: [{ hooks: [{ type: "command", command: `node ${ROOT}/hooks/journal.cjs turn-end` }] }],
    PostToolUse: [
      {
        matcher: "Bash",
        hooks: [{ type: "command", command: `node ${ROOT}/hooks/journal.cjs tool-used` }],
      },
    ],
  },
});

describe("generateOpencodeHooksBridge", () => {
  it("defines the V1 server and V2 setup entrypoints on the default plugin", () => {
    const generated = generateOpencodeHooksBridge(THREE_EVENT_HOOKS_JSON, "aidd-sample");

    expect(generated).toContain("export default {");
    expect(generated).toContain('id: "aidd-sample-hooks"');
    expect(generated).toContain("server: AiddSampleHooks");
    expect(generated).toContain("setup:");
  });

  it("generates a bridge module for a hooks.json naming all three mapped events", () => {
    const generated = generateOpencodeHooksBridge(THREE_EVENT_HOOKS_JSON, "aidd-sample");

    expect(generated).toMatchInlineSnapshot(`
      "// Generated by aidd from plugins/aidd-sample/hooks/hooks.json - do not edit by hand.
      // OpenCode's plugin loader scans no "hooks" family and this profile writes no hooks.json
      // (build.ts's skipHooksJson, translated here rather than skipped) - this file is the only
      // trigger this plugin's declared hooks have on OpenCode. See opencode-hooks-bridge.ts for
      // the mapping this generator applies and the measurements behind it.
      import { setupOpencodeEvents } from "../hooks/opencode-events.js";
      import { spawn } from "node:child_process";
      import { fileURLToPath } from "node:url";

      // Never process.execPath: OpenCode ships as its own standalone binary - that path names \`opencode\`
      // itself, not a Node runtime able to run this plugin's own hook scripts.
      const HOOKS_DIR = fileURLToPath(new URL("../hooks/aidd-sample/", import.meta.url));

      const SESSION_START = [{"script":"update_memory.js","args":[]}];
      const STOP = [{"script":"journal.cjs","args":["turn-end"]}];
      const POST_TOOL_USE = [{"script":"journal.cjs","args":["tool-used"],"matcher":"Bash"}];

      // Asynchronous on purpose: this can spawn one script per matching hook across every mapped
      // event, and blocking OpenCode's event loop once per hook would multiply the cost. A failed spawn (ENOENT, a killed timeout)
      // must not throw past this function - both listeners below, plus the caller's own
      // try/catch, exist because a spawn that never launches can still throw on the stdin write.
      function runHook(script, args, payload, directory) {
        const child = spawn("node", [HOOKS_DIR + script, ...args], {
          cwd: directory,
          stdio: ["pipe", "ignore", "ignore"],
          timeout: 5000,
        });
        child.on("error", () => {});
        child.stdin.on("error", () => {});
        child.stdin.end(JSON.stringify(payload));
      }

      /** Pure: \`session.idle\` -> every Stop hook's own {script, args, payload} - or \`[]\` for
       * any other event. Exported as a property (never a second named export - F6) so this
       * generated module's own mapping can be asserted without spawning anything. */
      function stopCallsFor(event, directory) {
        if (event?.type !== "session.idle") return [];
        const sessionId = event.properties?.sessionID;
        return STOP.map((hook) => ({
          script: hook.script,
          args: hook.args,
          payload: { hook_event_name: "Stop", session_id: sessionId ?? null, cwd: directory },
        }));
      }

      // Awaited, unlike runHook: the script has something the model must read.
      // Exit 2 puts it on stderr; exit 0 puts it in additionalContext on stdout.
      function answerFrom(code, stdout, stderr) {
        if (code === 2) return stderr.trim();
        if (code !== 0) return "";
        try {
          const output = JSON.parse(stdout);
          return String(output?.hookSpecificOutput?.additionalContext ?? output?.additionalContext ?? "").trim();
        } catch {
          return "";
        }
      }

      /** Runs one hook script with its payload on stdin and collects what it wrote. */
      function runCapture(script, args, payload, directory) {
        return new Promise((resolve) => {
          let stdout = "";
          let stderr = "";
          const child = spawn("node", [HOOKS_DIR + script, ...args], {
            cwd: directory,
            stdio: ["pipe", "pipe", "pipe"],
            timeout: 5000,
          });
          child.stdout.on("data", (chunk) => {
            stdout += chunk;
          });
          child.stderr.on("data", (chunk) => {
            stderr += chunk;
          });
          child.on("error", () => resolve({ code: null, stdout: "", stderr: "" }));
          child.on("close", (code) => resolve({ code, stdout, stderr }));
          child.stdin.on("error", () => {});
          child.stdin.end(JSON.stringify(payload));
        });
      }

      function answerOf(script, args, payload, directory) {
        return runCapture(script, args, payload, directory).then(({ code, stdout, stderr }) =>
          answerFrom(code, stdout, stderr)
        );
      }

      /** A Stop script's {"decision":"block","reason"} on stdout: the reason to keep working on. */
      function stopReasonOf(script, args, payload, directory) {
        return runCapture(script, args, payload, directory).then(({ code, stdout }) => {
          if (code !== 0) return "";
          try {
            const output = JSON.parse(stdout);
            return output?.decision === "block" ? String(output.reason ?? "").trim() : "";
          } catch {
            return "";
          }
        });
      }

      /** Pure: a finished tool call -> every PostToolUse hook whose matcher allows its tool. OpenCode
       * names the written file \`filePath\`; the scripts read Claude Code's \`file_path\`. */
      function postToolUseCallsFor(call, directory) {
        const tool = String(call?.tool ?? "");
        const args = call?.args;
        const matches = (matcher) =>
          !matcher || matcher.split("|").some((name) => name.toLowerCase() === tool.toLowerCase());
        const toolInput = typeof args?.filePath === "string" ? { ...args, file_path: args.filePath } : args;
        return POST_TOOL_USE.filter((hook) => matches(hook.matcher)).map((hook) => ({
          script: hook.script,
          args: hook.args,
          payload: {
            hook_event_name: "PostToolUse",
            session_id: call?.sessionID ?? null,
            cwd: directory,
            tool_name: tool,
            tool_input: toolInput,
          },
        }));
      }

      export const AiddSampleHooks = async (input) => {
        // Sessions whose last Stop asked the model to continue: their next Stop carries stop_hook_active.
        const continued = new Set();
        // SessionStart's own approximation (module doc comment above): fired once here, never
        // per session. Silent on purpose: a memory refresh
        // that breaks OpenCode's own startup is worse than one that never ran.
        try {
          for (const hook of SESSION_START) {
            runHook(
              hook.script,
              hook.args,
              { hook_event_name: "SessionStart", session_id: null, cwd: input.directory },
              input.directory
            );
          }
        } catch {
          // Silent on purpose - see above.
        }
        return {
          event: async ({ event }) => {
            try {
              const directory = event?.properties?.directory ?? input.directory;
              for (const call of stopCallsFor(event, directory)) {
                const sessionId = call.payload.session_id;
                const payload = { ...call.payload, stop_hook_active: continued.has(sessionId) };
                const reason = await stopReasonOf(call.script, call.args, payload, directory);
                if (!reason) {
                  continued.delete(sessionId);
                  continue;
                }
                continued.add(sessionId);
                // Not awaited: the prompt is the session's next turn, and this handler must not hold it.
                input.client.session
                  .promptAsync({ path: { id: sessionId }, body: { parts: [{ type: "text", text: reason }] } })
                  .catch(() => {});
              }
            } catch {
              // Silent on purpose - see above.
            }
          },
          "tool.execute.after": async (call, output) => {
            try {
              for (const hook of postToolUseCallsFor(call, input.directory)) {
                const answer = await answerOf(hook.script, hook.args, hook.payload, input.directory);
                if (answer) output.output = \`\${output.output ?? ""}\\n\\n\${answer}\`;
              }
            } catch {
              // Silent on purpose - see above.
            }
          },
        };
      };

      AiddSampleHooks.stopCallsFor = stopCallsFor;
      AiddSampleHooks.postToolUseCallsFor = postToolUseCallsFor;

      export default {
        id: "aidd-sample-hooks",
        server: AiddSampleHooks,
        setup: (ctx) => setupOpencodeEvents(ctx, AiddSampleHooks),
      };
      "
    `);
  });

  it("appends the additionalContext a PostToolUse script prints at exit 0", async () => {
    const directory = await mkdtemp(join(tmpdir(), "aidd-opencode-json-"));
    const generated = generateOpencodeHooksBridge(
      JSON.stringify({
        hooks: { PostToolUse: [{ hooks: [{ command: `node ${ROOT}/hooks/check.cjs` }] }] },
      }),
      "probe"
    );
    try {
      await mkdir(join(directory, "hooks", "probe"), { recursive: true });
      await mkdir(join(directory, "plugin"));
      await writeFile(
        join(directory, "hooks", "opencode-events.js"),
        "export function setupOpencodeEvents() {}\n"
      );
      await writeFile(
        join(directory, "hooks", "probe", "check.cjs"),
        'process.stdin.resume(); process.stdin.on("end", () => { process.stdout.write(JSON.stringify({ hookSpecificOutput: { hookEventName: "PostToolUse", additionalContext: "fix it" } })); });'
      );
      const modulePath = join(directory, "plugin", "bridge.mjs");
      await writeFile(modulePath, generated ?? "");
      const module = await import(pathToFileURL(modulePath).href);
      const hooks = await module.default.server({ directory });
      const output = { output: "edited" };
      await hooks["tool.execute.after"](
        { tool: "edit", sessionID: "s", args: { filePath: "a.md" } },
        output
      );
      expect(output.output).toBe("edited\n\nfix it");
    } finally {
      await rm(directory, { recursive: true, force: true });
    }
  });

  it("sends a Stop script's block reason as the next prompt, and tells the next Stop it is a continuation", async () => {
    const directory = await mkdtemp(join(tmpdir(), "aidd-opencode-stop-"));
    const log = join(directory, "stop.jsonl");
    const generated = generateOpencodeHooksBridge(
      JSON.stringify({
        hooks: { Stop: [{ hooks: [{ command: `node ${ROOT}/hooks/stop.cjs` }] }] },
      }),
      "probe"
    );
    try {
      await mkdir(join(directory, "hooks", "probe"), { recursive: true });
      await mkdir(join(directory, "plugin"));
      await writeFile(
        join(directory, "hooks", "opencode-events.js"),
        "export function setupOpencodeEvents() {}\n"
      );
      await writeFile(
        join(directory, "hooks", "probe", "stop.cjs"),
        `let input = ""; process.stdin.on("data", (c) => { input += c; }); process.stdin.on("end", () => {
          const payload = JSON.parse(input);
          require("node:fs").appendFileSync(${JSON.stringify(log)}, JSON.stringify(payload) + "\\n");
          if (!payload.stop_hook_active) process.stdout.write(JSON.stringify({ decision: "block", reason: "fix it" }));
        });`
      );
      const modulePath = join(directory, "plugin", "bridge.mjs");
      await writeFile(modulePath, generated ?? "");
      const module = await import(pathToFileURL(modulePath).href);
      const prompts: unknown[] = [];
      const client = {
        session: { promptAsync: async (request: unknown) => void prompts.push(request) },
      };
      const hooks = await module.default.server({ directory, client });
      const idle = { event: { type: "session.idle", properties: { sessionID: "s1" } } };

      await hooks.event(idle);
      await hooks.event(idle);

      expect(prompts).toStrictEqual([
        { path: { id: "s1" }, body: { parts: [{ type: "text", text: "fix it" }] } },
      ]);
      const payloads = (await readFile(log, "utf8"))
        .trim()
        .split("\n")
        .map((line) => JSON.parse(line));
      expect(payloads.map((payload) => payload.stop_hook_active)).toStrictEqual([false, true]);
    } finally {
      await rm(directory, { recursive: true, force: true });
    }
  });

  it("returns null for a hooks.json naming only an unmapped event", () => {
    const hooksJson = JSON.stringify({
      hooks: { PreToolUse: [{ hooks: [{ type: "command", command: `${ROOT}/hooks/check.sh` }] }] },
    });

    expect(generateOpencodeHooksBridge(hooksJson, "aidd-test")).toBeNull();
  });

  it("returns null for a hooks.json with no hooks at all", () => {
    expect(generateOpencodeHooksBridge(JSON.stringify({ hooks: {} }), "aidd-test")).toBeNull();
  });

  it("generates a bridge for a plugin whose hooks name only Stop", () => {
    const hooksJson = JSON.stringify({
      hooks: {
        Stop: [
          { hooks: [{ type: "command", command: `node ${ROOT}/hooks/journal.cjs turn-end` }] },
        ],
      },
    });

    expect(generateOpencodeHooksBridge(hooksJson, "aidd-test")).toContain(
      'const SESSION_START = [];\nconst STOP = [{"script":"journal.cjs","args":["turn-end"]}];\nconst POST_TOOL_USE = [];\n'
    );
  });

  it("generates a bridge for a plugin whose hooks name only PostToolUse", () => {
    const hooksJson = JSON.stringify({
      hooks: {
        PostToolUse: [
          { hooks: [{ type: "command", command: `node ${ROOT}/hooks/journal.cjs tool-used` }] },
        ],
      },
    });

    expect(generateOpencodeHooksBridge(hooksJson, "aidd-test")).toContain(
      'const SESSION_START = [];\nconst STOP = [];\nconst POST_TOOL_USE = [{"script":"journal.cjs","args":["tool-used"]}];\n'
    );
  });

  it("names the bridge's export after the plugin even when its name holds an empty segment", () => {
    expect(generateOpencodeHooksBridge(THREE_EVENT_HOOKS_JSON, "aidd--sample")).toContain(
      "export const AiddSampleHooks = async (input) => {"
    );
  });

  it("drops a hook whose command does not invoke node against its own hooks/ script", () => {
    const hooksJson = JSON.stringify({
      hooks: { Stop: [{ hooks: [{ type: "command", command: `${ROOT}/hooks/check.sh` }] }] },
    });

    expect(generateOpencodeHooksBridge(hooksJson, "aidd-test")).toBeNull();
  });
});

describe("parseHooksJsonForBridge", () => {
  const stopCallsOf = (command: string) =>
    parseHooksJsonForBridge(
      JSON.stringify({ hooks: { Stop: [{ hooks: [{ type: "command", command }] }] } })
    ).stop;

  it("splits a hook's arguments on any run of whitespace", () => {
    expect(stopCallsOf(`node ${ROOT}/hooks/journal.cjs turn-end   --quiet`)).toStrictEqual([
      { script: "journal.cjs", args: ["turn-end", "--quiet"] },
    ]);
  });

  it("reads a command written with surrounding whitespace", () => {
    expect(stopCallsOf(`  node ${ROOT}/hooks/journal.cjs  `)).toStrictEqual([
      { script: "journal.cjs", args: [] },
    ]);
  });

  it("skips a hook that carries no command, keeping the ones beside it", () => {
    const hooksJson = JSON.stringify({
      hooks: {
        Stop: [
          {
            hooks: [
              { type: "prompt" },
              { type: "command", command: `node ${ROOT}/hooks/journal.cjs` },
            ],
          },
        ],
      },
    });

    expect(parseHooksJsonForBridge(hooksJson).stop).toStrictEqual([
      { script: "journal.cjs", args: [] },
    ]);
  });
});
