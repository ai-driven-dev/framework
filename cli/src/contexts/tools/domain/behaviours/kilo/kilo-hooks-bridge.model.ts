/**
 * Kilo loads JavaScript modules from `.kilo/plugin/` and requires a default descriptor with
 * `{ id, server }`. Declarative hooks.json has no Kilo runtime, so this generator turns its
 * replayable commands into that native module. Kilo 7.7.5 delivers session.created and
 * session.idle through its event hook; a SessionStart answer reaches the model through
 * experimental.chat.system.transform; PostToolUse runs from tool.execute.after, which waits
 * for the script and appends its exit-2 stderr to the tool's output for the model to read; an
 * answer the script marks required is also queued as the session's next prompt, which supersedes
 * what is left of the turn it interrupts.
 * Matchers ignore case, since Kilo names its tools in lowercase.
 */

import { type BridgeParts, generateBridge } from "../../bridges/event-bridge.js";

const KILO_HOST = {
  identifierSuffix: "KiloHooks",
  render: (parts: BridgeParts): string => `// Generated by aidd: ${parts.plugin}/hooks/hooks.json.
${parts.nodeImports}

${parts.hooksDir}
${parts.callTables}

// Exit 2 puts the answer on stderr; exit 0 puts it in additionalContext on stdout.
${parts.answerFrom}

/** A Stop script's {"decision":"block","reason"} on stdout: the reason to keep working on. */
function stopReasonOf(script, args, payload, directory) {
  return new Promise((resolve) => {
    let stdout = "";
${parts.spawnHook(4, '["pipe", "pipe", "ignore"]')}
    child.stdout.on("data", (chunk) => { stdout += chunk; });
    child.on("error", () => resolve(""));
    child.on("close", (code) => {
      if (code !== 0) return resolve("");
      try {
        const output = JSON.parse(stdout);
        resolve(${parts.stopReason});
      } catch {
        resolve("");
      }
    });
${parts.feedStdin(4)}
  });
}

function answerOf(script, args, payload, directory) {
  return new Promise((resolve) => {
    let stdout = "";
    let stderr = "";
${parts.spawnHook(4, '["pipe", "pipe", "pipe"]')}
    // A spawn that never launches emits both an error and a close: one report per script.
    let failed = false;
    const fail = (error) => {
      if (failed) return;
      failed = true;
      reportHookFailure(script, error);
      resolve({ text: "", required: false });
    };
    child.stdout.on("data", (chunk) => { stdout += chunk; });
    child.stderr.on("data", (chunk) => { stderr += chunk; });
    child.on("error", fail);
    child.on("close", (code, signal) => {
      if ((code !== 0 && code !== 2) || signal !== null) {
        fail("exited with code " + String(code) + (signal === null ? "" : " (" + signal + ")"));
        return;
      }
      resolve(answerFrom(code, stdout, stderr));
    });
${parts.feedStdin(4)}
  });
}

function reportHookFailure(script, error) {
  console.warn("[aidd] Kilo hook " + script + " failed: " + String(error));
}

function sessionStartCallsFor(event, directory) {
  if (event?.type !== "session.created") return [];
  return SESSION_START.map((hook) => ({
    script: hook.script,
    args: hook.args,
    payload: { hook_event_name: "SessionStart", session_id: event.properties?.sessionID ?? null, cwd: event.properties?.info?.directory ?? directory },
  }));
}

const BRIDGE_PROMPT = { aidd: "bridge-prompt" };

const ${parts.identifier} = async ({ directory, client }) => {
  const sessions = new Map();
  return {
  event: async ({ event }) => {
    try {
      const properties = event?.properties;
      const id = properties?.sessionID;
      if (typeof id !== "string") return;
      if (event?.type === "session.deleted") { sessions.delete(id); return; }
      if (!sessions.has(id)) sessions.set(id, { started: false, idle: false, continued: false, directory });
      const session = sessions.get(id);
      let calls = [];
      if (event?.type === "session.created" && !session.started) {
        session.started = true;
        session.directory = properties?.info?.directory ?? directory;
        calls = sessionStartCallsFor(event, session.directory);
      } else if (event?.type === "session.status" && properties?.status?.type === "busy") {
        session.idle = false;
      } else if (event?.type === "session.idle" && !session.idle) {
        session.idle = true;
        // Limit: one Stop hook per plugin; with several, the last verdict decides the continuation.
        for (const hook of STOP) {
          const payload = { hook_event_name: "Stop", session_id: id, cwd: session.directory, stop_hook_active: session.continued };
          const reason = await stopReasonOf(hook.script, hook.args, payload, session.directory);
          session.continued = reason !== "";
          // Not awaited: the prompt is the session's next turn, and this handler must not hold it.
          // Kilo 7.8.27's \`run\` waits for the queue to drain, so the follow-up lands there too; awaiting
          // it from \`dispose\` fails with an UnknownError. 7.7.5 lost it in \`run\`.
          if (reason) {
            client.session
              .promptAsync({ path: { id }, body: { parts: [{ type: "text", text: reason, metadata: BRIDGE_PROMPT }] } })
              .catch((error) => reportHookFailure(hook.script, "follow-up not delivered: " + String(error)));
          }
        }
      }
      // Not awaited: this handler must not hold the host's events. The session's first turn awaits it.
      if (calls.length > 0) {
        session.context = Promise.all(
          calls.map((call) => answerOf(call.script, call.args, call.payload, call.payload.cwd))
        ).then((answers) => answers.map((answer) => answer.text).filter(Boolean).join("\\n\\n"));
      }
    } catch (error) {
      console.warn("[aidd] Kilo hook dispatch failed: " + String(error));
    }
  },
  // What SessionStart answered reaches the model through its session's system prompt, every turn.
  "experimental.chat.system.transform": async (input, output) => {
    const context = await sessions.get(input?.sessionID)?.context;
    if (context) output.system.push(context);
  },
  // A user's message starts a new turn. Kilo hands every plugin every message, so a prompt a
  // bridge sent (a Stop continuation or a queued finding), this one's or another plugin's, is
  // recognised by its mark and is not one.
  "chat.message": async (input, output) => {
    const session = sessions.get(input?.sessionID);
    if (!session) return;
    if (!output?.parts?.some((part) => part?.metadata?.aidd === BRIDGE_PROMPT.aidd)) session.continued = false;
  },
  "tool.execute.after": async (call, output) => {
    try {
      const tool = String(call?.tool ?? "");
      const sessionId = call?.sessionID;
      const cwd = sessions.get(sessionId)?.directory ?? directory;
      // Kilo names the written file filePath; the scripts read Claude Code's file_path.
      const args = call?.args;
      ${parts.toolInput}
      for (const hook of POST_TOOL_USE.filter(hook => !hook.matcher || hook.matcher.split("|").some(name => name.toLowerCase() === tool.toLowerCase()))) {
        const { text: answer, required } = await answerOf(hook.script, hook.args, { hook_event_name: "PostToolUse", session_id: sessionId ?? null, cwd, tool_name: tool, tool_input: toolInput }, cwd);
        ${parts.appendAnswer}
${parts.queueRequired(8, { client: "client", session: "sessionId", mark: "BRIDGE_PROMPT" })}
      }
    } catch (error) {
      console.warn("[aidd] Kilo hook dispatch failed: " + String(error));
    }
  },
  };
};

${parts.identifier}.sessionStartCallsFor = sessionStartCallsFor;

export default { id: "${parts.plugin}-hooks", server: ${parts.identifier} };
`,
};

/** Generates Kilo's default descriptor; failed hooks report without blocking its session. */
export function generateKiloHooksBridge(rawHooksJson: string, plugin: string): string | null {
  return generateBridge(KILO_HOST, rawHooksJson, plugin);
}
